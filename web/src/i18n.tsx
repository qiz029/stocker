export const dicts: Record<Lang, Record<MsgKey, string>> = { en, zh };

export type TFunc = (key: MsgKey, params?: Record<string, string | number>) => string;

/** Standalone translator for a fixed language (non-React code and tests). */
export function tFor(lang: Lang): TFunc {
  return (key, params) => {
    let s = dicts[lang][key];
    if (params) for (const [k, v] of Object.entries(params)) s = s.replaceAll(`{${k}}`, String(v));
    return s;
  };
}

type I18nCtxValue = { lang: Lang; setLang: (l: Lang) => void; t: TFunc };

/* Default context = English, so components rendered without the provider
   (e.g. in unit tests) still work. */
const I18nCtx = createContext<I18nCtxValue>({ lang: "en", setLang: () => {}, t: tFor("en") });

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>(() =>
    localStorage.getItem(STORAGE_KEY) === "zh" ? "zh" : "en");

  useEffect(() => {
    document.documentElement.lang = lang === "zh" ? "zh-CN" : "en";
    document.title = dicts[lang]["app.title"];
  }, [lang]);

  const setLang = (l: Lang) => {
    localStorage.setItem(STORAGE_KEY, l);
    setLangState(l);
  };

  return <I18nCtx.Provider value={{ lang, setLang, t: tFor(lang) }}>{children}</I18nCtx.Provider>;
}

export const useT = () => useContext(I18nCtx);

/** Pick the English variant of a server-provided string in en mode, falling
    back to the Chinese original when the English field is missing/empty. */
export function pickL(lang: Lang, zh: string, en?: string | null): string {
  return lang === "en" && en ? en : zh;
}

/** Media outlet display name; unknown ids pass through unchanged. */
export function mediaName(id: string, t: TFunc): string {
  const key = `media.${id}` as MsgKey;
  return key in zh ? t(key) : id;
}

export function LangSwitch() {
  const { lang, setLang } = useT();
  return (
    <div className="lang-switch">
      <button className={lang === "zh" ? "on" : ""} onClick={() => setLang("zh")}>中文</button>
      <button className={lang === "en" ? "on" : ""} onClick={() => setLang("en")}>EN</button>
    </div>
  );
}
